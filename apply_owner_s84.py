#!/usr/bin/env python3
"""
apply_owner_s84.py -- NEEC: the generator that applies the owner's items and closes two consistency gaps (Session 84, ledger S68)
=============================================================================================================================
Session 83's adjudication put four readings to the owner; the owner answered (D66, D67). Session 84 also re-read the two
clauses of CCO-PTF-CIP-SZH's C3.4 that rested on the unit's own text, and read Participatory Economics' C1.2b by the
adjudication's rule 4 (owner_s84.py; the record NEEC_OwnerItems_s84.md). final_pass.settled_state() lays the layer over the
adjudicated state; this script writes, never by hand:

  neec_corpus_v2.json         the 23 entries on the 29 criteria, with the layer applied
  neec_scores_v2.csv          their totals, domain sums, failures and tiers
  summary_blocks_v2.json      the site's per-entry blocks (each unit's alternative is its close call)
  NEEC_OwnerItems_s84.md      the generated tables only, between the record's '<!-- generated:NAME -->' and
                              '<!-- /generated -->' markers: the changes, the standing, the standing with and without
                              each owner decision, the summary

Every displayed name comes from display_names.py (the entry renamed CCO-PTF-PTH-SZH-CIP, ledger D68, decision 84.5); an
entry's key and code do not change. The Session 83 state is kept as neec_corpus_v2_s83_snapshot.json and its two companions
(apply_adjudication_s83.py writes them).

Usage: python3 apply_owner_s84.py           write the three files and the record's generated tables
       python3 apply_owner_s84.py --check   recompute and compare with the files on disk (exit 1 on any difference); also
                                            checks the changed cells, the display name, totals, tiers and the standing
Prints file names and summaries only. Deterministic.
"""
import csv
import io
import json
import os
import re
import sys
from contextlib import redirect_stdout

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apply_pass_s65 as ap  # noqa: E402
import display_names as dn  # noqa: E402
import final_pass as fp  # noqa: E402
import pass_common as pc  # noqa: E402

OUT = {"corpus": "neec_corpus_v2.json", "csv": "neec_scores_v2.csv", "blocks": "summary_blocks_v2.json"}
SNAP = {"corpus": "neec_corpus_v2_s83_snapshot.json", "csv": "neec_scores_v2_s83_snapshot.csv",
        "blocks": "summary_blocks_v2_s83_snapshot.json"}
S78 = "neec_corpus_v2_s78_snapshot.json"
RECORD = "NEEC_OwnerItems_s84.md"
NOTE = ("NEEC v1 scores re-estimated on the v2.0 criteria by the rescoring pass (NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), "
        "the three new criteria scored in Session 65, re-read blind in Sessions 71 to 77 (NEEC_BlindReview_s71.md to "
        "NEEC_BlindReview_s77.md), with the owner's decisions 79.1 to 79.4 (NEEC_OwnerDecisions_s79.md), the adjudication "
        "of the outside review (NEEC_Adjudication_s83.md) and the owner's items of Session 84 (NEEC_OwnerItems_s84.md), "
        "applied by apply_owner_s84.py; provisional until Report and Paper v2.0")
DESCRIPTION = ("The NEEC corpus on the v2.0 criteria (29 criteria in five domains): the published 26-criterion vectors with the "
               "rescoring pass applied, the three new criteria scored, the blind re-read's final readings (Sessions 71 to 77), "
               "the owner's decisions 79.1 to 79.4 (Session 79), the adjudication of the outside review (Session 83) and the "
               "owner's items with two consistency readings (Session 84) laid over them. Generated by apply_owner_s84.py; "
               "never edited by hand. Scores: 1.0 pass, 0.5 partial, 0.0 structural failure; totals, failures and tiers "
               "follow by protocol section 2, with integer failure bands 0-2, 3-5 and 6+ on the 29 (decision 45.1).")
GEN = re.compile(r"(<!-- generated:(\w+) -->\n)(.*?)(<!-- /generated -->)", re.S)
# the owner's decisions and the cells each decided: (decision, cells, the value each cell takes without the decision, label)
WITHOUT = (("58.1", [("CCO", "C3.2")], 0.5, "58.1 (C3.2)"),
           ("79.1", [("CCO", "C1.2a")], 0.5, "79.1 (C1.2a)"),
           ("79.2", [("CCO", "C2.5")], 0.5, "79.2 (C2.5)"),
           ("79.3", [("CCO", "C3.4")], 0.5, "79.3 (C3.4)"),
           ("79.4", [("INT", "C3.4"), ("OS", "C3.4")], 0.5, "79.4 (C3.4 for Integral and Ostrom)"),
           ("D66", [("DG", "C3.4"), ("PE", "C3.4")], 1.0, "D66 (C3.4 for Degrowth and PE)"),
           ("D67", [("CCO", "C2.2"), ("CCO", "C5.3")], 1.0, "D67 (C2.2 and C5.3)"))
# on the readings alone: every cell at its reading, without the owner. The five raises are reversed; D66 and D67 applied the
# readings, so their cells already stand there (reversing them would restore 1.0s the readings do not give)
READINGS = ("58.1", "79.1", "79.2", "79.3", "79.4")


def state():
    with redirect_stdout(io.StringIO()):
        p = pc.Pass()
        units, part_of, new_units, new_part_of, _, _, _ = fp.settled_state(p)
        adj = pc.load("adjudicate_s83", "adjudicate_s83.py")
        ow = pc.load("owner_s79", "owner_s79.py")
        s84 = pc.load("owner_s84", "owner_s84.py")
    return p, units, part_of, new_units, new_part_of, adj, ow, s84


def build():
    p, units, part_of, new_units, new_part_of, adj, ow, s84 = state()
    rec = {t: r for t, _, _, r, _ in fp.GROUPS}
    rec[ow.TAG] = ow.RECORD
    rec[adj.TAG] = adj.RECORD
    rec[s84.TAG] = s84.RECORD

    def record_of(c, k):
        tag = new_part_of.get((c, k)) or part_of.get((c, k))
        if tag in rec:
            return rec[tag]
        if (c, k) in new_units or k in p.mods[-1].CRITS:
            return "NEEC_Rescoring_s65.md"
        return "the rescoring record of the part that read it"

    def row_notes(changed):
        return [f"Rescoring pass, blind re-read, the owner's decisions, the adjudication of the outside review and the owner's "
                f"items applied (Sessions 65, 71 to 77, 79, 83 and 84; generators Sessions 78, 79, 83 and 84): {changed} of the "
                f"26 published scores changed; C2.6, C3.6 and C4.6 scored for the first time",
                "Provisional until Report and Paper v2.0; every unit's reading is in the rescoring records "
                "(NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), the blind records (NEEC_BlindReview_s71.md to "
                "NEEC_BlindReview_s77.md), NEEC_OwnerDecisions_s79.md, NEEC_Adjudication_s83.md and NEEC_OwnerItems_s84.md."]
    texts, _, vec, _ = ap.build({"units": units, "new_units": new_units, "part_of": part_of, "note": NOTE,
                                 "description": DESCRIPTION, "row_notes": row_notes, "record_of": record_of})
    out = {}
    for k in ("corpus", "blocks"):
        obj = dn.rename_obj(json.loads(texts[ap.OUT[k]]))
        out[OUT[k]] = json.dumps(obj, indent=1, ensure_ascii=False) + "\n"
    out[OUT["csv"]] = dn.rename(texts[ap.OUT["csv"]])
    snap = json.load(open(os.path.join(HERE, SNAP["corpus"]), encoding="utf-8"))
    v_old = {e["code"]: e["vector"] for e in snap["entries"]}
    return out, p, adj, ow, s84, units, new_units, vec, v_old


def without(vec, decisions):
    """The vectors with the named owner decisions reversed (each cell to the value it takes without the decision)."""
    v = {c: dict(x) for c, x in vec.items()}
    for d, cells, val, _ in WITHOUT:
        if d in decisions:
            for c, k in cells:
                v[c][k] = val
    return v


def tables(p, s84, vec, v_old):
    """The record's generated tables, by name."""
    f1 = pc.f1
    names = {c: dn.DISPLAY.get(c, n) for c, n in p.names.items()}
    crit = json.load(open(os.path.join(HERE, "criteria.json"), encoding="utf-8"))
    cname = {c["id"]: c["name"] for c in crit["criteria"]}
    order = [c for d in crit["domains"] for c in d["criteria"]]
    out = {}
    def dec(k):
        return (s84.OWNER.get(k) or s84.REVISIONS.get(k) or s84.UNITS.get(k))["decision"]
    keys = sorted(set(s84.OWNER) | set(s84.REVISIONS) | set(s84.UNITS), key=lambda k: (dec(k), p.order.index(k[0]), order.index(k[1])))
    rows = ["| Decision | Criterion | Entry | Before | After | What changed |", "|---|---|---|---:|---:|---|"]
    for c, k in keys:
        if (c, k) in s84.OWNER:
            d, what = s84.OWNER[(c, k)]["decision"], f"the owner's answer to {s84.OWNER[(c, k)]['ledger']}: the adjudication's reading applied"
        elif (c, k) in s84.REVISIONS:
            d, what = s84.REVISIONS[(c, k)]["decision"], ("clauses " + " and ".join(str(n) for n in s84.REVISIONS[(c, k)]["clauses"])
                                                           + " re-read on cited sources; the verdict holds")
        else:
            d, what = s84.UNITS[(c, k)]["decision"], "read by rule 4 of decision 83.4 (one reading per class)"
        rows.append(f"| {d} | {k} {cname[k]} | {names[c]} | {f1(v_old[c][k])} | {f1(vec[c][k])} | {what} |")
    out["changes"] = "\n".join(rows)
    now = {c: sum(v.values()) for c, v in vec.items()}
    old = {c: sum(v.values()) for c, v in v_old.items()}
    fn = {c: sum(1 for x in v.values() if x == 0.0) for c, v in vec.items()}
    fo = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_old.items()}
    rk_o, rk_n = pc.ranks(old), pc.ranks(now)
    rows = ["| Entry | Session 83 (rank) | Session 84 (rank) | Change | Failures | Tier |", "|---|---:|---:|---:|---:|---|"]
    for c in sorted(p.order, key=lambda x: (-now[x], p.order.index(x))):
        tier = pc.tier(fn[c]) + ("" if pc.tier(fn[c]) == pc.tier(fo[c]) else f" (was {pc.tier(fo[c])})")
        rows.append(f"| {names[c]} | {f1(old[c])} ({rk_o[c]}) | {f1(now[c])} ({rk_n[c]}) | {f1(now[c] - old[c])} | "
                    f"{fo[c]} to {fn[c]} | {tier} |")
    out["standing"] = "\n".join(rows)
    cols = [("Session 84", ())] + [(f"without {lab}", (d,)) for d, _, _, lab in WITHOUT] + \
           [("on the readings alone (no owner decision)", READINGS)]
    tots = []
    for _, ds in cols:
        t = {c: sum(v.values()) for c, v in without(vec, ds).items()}
        tots.append((t, pc.ranks(t)))
    rows = ["| Entry | " + " | ".join(lab for lab, _ in cols) + " |", "|---|" + "---:|" * len(cols)]
    for c in sorted(p.order, key=lambda x: (-now[x], p.order.index(x)))[:10]:
        rows.append(f"| {names[c]} | " + " | ".join(f"{f1(t[c])} ({r[c]})" for t, r in tots) + " |")
    out["withwithout"] = "\n".join(rows)
    first = [c for c in p.order if now[c] == max(now.values())]
    second = max(now[c] for c in p.order if c not in first)
    at2 = [c for c in p.order if now[c] == second]
    alone = tots[-1][0]
    top = max(alone.values())
    out["summary"] = (f"The layer writes {len(keys)} units: {len(s84.OWNER)} owner items applied (decisions 84.1 and 84.2), "
                      f"{len(s84.REVISIONS)} clause revision with the verdict held (84.3) and {len(s84.UNITS)} class reading "
                      f"(84.4); {sum(1 for c, k in keys if vec[c][k] != v_old[c][k])} verdicts change. First place: "
                      f"{', '.join(names[c] for c in first)} at {f1(now[first[0]])}, ahead of {', '.join(names[c] for c in at2)} "
                      f"at {f1(second)}; tier changes: "
                      f"{', '.join(names[c] for c in p.order if pc.tier(fn[c]) != pc.tier(fo[c])) or 'none'}. On the readings "
                      f"alone (no owner decision: the raises of 58.1 and 79.1 to 79.4 reversed): {', '.join(names[c] for c in p.order if alone[c] == top)} "
                      f"first at {f1(top)}, {names['CCO']} {f1(alone['CCO'])}.")
    return out


def record_text(gen):
    path = os.path.join(HERE, RECORD)
    if not os.path.isfile(path):
        return None, None
    old = open(path, encoding="utf-8").read()
    new = GEN.sub(lambda m: m.group(1) + gen[m.group(2)] + "\n" + m.group(4), old)
    return old, new


def main():
    texts, p, adj, ow, s84, units, new_units, vec, v_old = build()
    gen = tables(p, s84, vec, v_old)
    old_rec, new_rec = record_text(gen)
    if "--check" in sys.argv[1:]:
        ok = True

        def check(cond, text, detail=""):
            nonlocal ok
            print(f"  {'PASS' if cond else 'FAIL'} {text}" + ("" if cond or not detail else f": {detail}"))
            ok = ok and bool(cond)
        for name, t in texts.items():
            good = os.path.isfile(os.path.join(HERE, name)) and open(os.path.join(HERE, name), encoding="utf-8").read() == t
            check(good, f"{name} equals what the generator produces")
        names_in = {m.group(2) for m in GEN.finditer(old_rec or "")}
        check(old_rec is not None and old_rec == new_rec and names_in == set(gen),
              f"{RECORD} carries every generated table ({', '.join(sorted(gen))}) as the generator produces it")
        corpus = json.loads(open(os.path.join(HERE, OUT["corpus"]), encoding="utf-8").read())
        v_now = {e["code"]: e["vector"] for e in corpus["entries"]}
        allu = {**units, **new_units}
        check(all(v_now[c][k] == u["verdict"] for (c, k), u in allu.items()),
              f"the corpus carries the verdict of each of the {len(allu)} units")
        moved = {(c, k) for c in v_now for k in v_now[c] if v_now[c][k] != v_old[c][k]}
        want = set(s84.OWNER) | set(s84.UNITS)
        check(moved == want and all(v_now[c][k] == 0.5 and v_old[c][k] == 1.0 for c, k in moved)
              and all(v_now[c][k] == adj.OWNER[(c, k)]["proposed"] for c, k in s84.OWNER)
              and all(v_now[c][k] == v_old[c][k] == 1.0 for c, k in s84.REVISIONS),
              f"the corpus differs from the Session 83 snapshot in exactly the {len(want)} cells the layer changes, each 1.0 to "
              "0.5 (the four owner items as the adjudication reads them, and Participatory Economics' C1.2b); "
              "CCO-PTF-PTH-SZH-CIP's C3.4 holds at 1.0")
        e = {x["code"]: x for x in corpus["entries"]}
        raw = "".join(texts.values())
        check(e["CCO"]["display_name"] == dn.DISPLAY["CCO"] and e["CCO"]["key"] == dn.OLD["CCO"]
              and dn.OLD["CCO"] not in raw.replace(f'"key": "{dn.OLD["CCO"]}"', ""),
              "the entry is shown as CCO-PTF-PTH-SZH-CIP in the corpus, the CSV and the blocks; its key keeps the identifier")
        rows = {r["system"]: r for r in csv.DictReader(io.StringIO(texts[OUT["csv"]]))}
        check(all(abs(float(rows[e[c]["display_name"]]["total_score"]) - sum(v_now[c].values())) < 1e-9
                  and int(rows[e[c]["display_name"]]["failures"]) == sum(1 for x in v_now[c].values() if x == 0.0)
                  for c in v_now),
              "each total and failure count in the CSV is the sum of the corpus vector")
        blocks = json.loads(texts[OUT["blocks"]])
        flagged = {(b["code"], f["criterion"]): f["alternatives"] for b in blocks for f in b["flags"]}
        check(all(b["vector"] == v_now[b["code"]] and b["summary"]["total"] == sum(v_now[b["code"]].values()) for b in blocks)
              and all(flagged.get(k) == [allu[k]["flag"][0][0]] for k in want if allu[k]["flag"]),
              "each block's vector and total equal the corpus's, and each changed unit with a flag is a close call toward "
              "its alternative")
        now = {c: sum(v.values()) for c, v in v_now.items()}
        fails = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_now.items()}
        fails_old = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_old.items()}
        top = sorted(now, key=lambda c: -now[c])
        check(top[0] == "CCO" and abs(now["CCO"] - 16.5) < 1e-9 and abs(now["PE"] - 15.5) < 1e-9
              and max(now[c] for c in now if c != "CCO") == 15.5,
              "CCO-PTF-PTH-SZH-CIP is first alone at 16.5; Participatory Economics 15.5, level with the next")
        check(all(pc.tier(fails[c]) == pc.tier(fails_old[c]) for c in now), "no tier changes")
        alone = {c: sum(v.values()) for c, v in without(v_now, READINGS).items()}
        check(abs(alone["CCO"] - 14.5) < 1e-9 and max(alone.values()) == 15.5 and alone["CCO"] < max(alone.values()),
              "on the readings alone (the raises of 58.1 and 79.1 to 79.4 reversed), CCO-PTF-PTH-SZH-CIP stands at 14.5, below the "
              "first place at 15.5")
        print("\nOWNER ITEMS OF SESSION 84: APPLICATION CHECKED." if ok else "\nOWNER ITEMS OF SESSION 84: CHECKS FAILED.")
        return 0 if ok else 1
    for name, t in texts.items():
        open(os.path.join(HERE, name), "w", encoding="utf-8").write(t)
        print(f"  wrote {name}")
    if new_rec is not None and new_rec != old_rec:
        open(os.path.join(HERE, RECORD), "w", encoding="utf-8").write(new_rec)
        print(f"  wrote the generated tables of {RECORD}")
    print("  " + gen["summary"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
