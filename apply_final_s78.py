#!/usr/bin/env python3
"""
apply_final_s78.py -- NEEC stage 3b: the generator that applies the blind re-read's final readings (Session 78, ledger S61)
==========================================================================================================================
Sessions 71 to 77 re-read the units of seven groups blind (decisions 69.1, 69.2; ledger D52, D53); each session's script ends in a
FINAL dictionary of the readings that stand, and each recorded its verdict changes for this session to apply (decisions 72.1, 74.1,
76.1, 77.3; ledger D55 to D57). This script lays them over the rescoring pass (final_pass.py) and writes, never by hand:

  neec_corpus_v2.json       the 23 entries on the 29 criteria of criteria.json, with the final readings
  neec_scores_v2.csv        their totals, domain sums, failures and tiers
  summary_blocks_v2.json    the site's per-entry blocks: the flagged calls (the final readings') and the joint readings
  NEEC_FinalApplication_s78.md   the record: the groups applied, every verdict change, the standing table, the tier changes, the
                            first place and the CCO-PTF-CIP-SZH units (none changes)

It reuses apply_pass_s65.build(), which wrote the same three files from the pass alone; those files are kept as
neec_corpus_v2_s65_snapshot.json, neec_scores_v2_s65_snapshot.csv and summary_blocks_v2_s65_snapshot.json (the blind scripts compare
their priors with them). The files the pass was computed against (neec_corpus.json and the others) are not changed.

Usage: python3 apply_final_s78.py           write the four files
       python3 apply_final_s78.py --check   recompute and compare with the files on disk (exit 1 on any difference); also checks
                                            the corpus against every unit, the changes against the Session 65 snapshot and each
                                            group's recorded count, the tier changes, the first place and the CCO units
Prints file names and summaries only. Deterministic.
"""
import csv
import io
import json
import os
import sys
from contextlib import redirect_stdout

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apply_pass_s65 as ap  # noqa: E402
import final_pass as fp  # noqa: E402
import pass_common as pc  # noqa: E402

OUT = {"corpus": "neec_corpus_v2.json", "csv": "neec_scores_v2.csv", "blocks": "summary_blocks_v2.json",
       "record": "NEEC_FinalApplication_s78.md"}
SNAP = {"corpus": ap.OUT["corpus"], "csv": ap.OUT["csv"], "blocks": ap.OUT["blocks"]}
NOTE = ("NEEC v1 scores re-estimated on the v2.0 criteria by the rescoring pass (NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), "
        "the three new criteria scored in Session 65, and re-read blind in Sessions 71 to 77 (NEEC_BlindReview_s71.md to "
        "NEEC_BlindReview_s77.md), applied by apply_final_s78.py; provisional until Report and Paper v2.0")
DESCRIPTION = ("The NEEC corpus on the v2.0 criteria (29 criteria in five domains): the published 26-criterion vectors with the "
               "rescoring pass applied, the three new criteria scored, and the blind re-read's final readings (Sessions 71 to 77) "
               "laid over them. Generated by apply_final_s78.py from neec_corpus.json, the pass's readings and the blind "
               "groups' final readings; never edited by hand. Scores: 1.0 pass, 0.5 partial, 0.0 structural failure; totals, "
               "failures and tiers follow by protocol section 2, with integer failure bands 0-2, 3-5 and 6+ on the 29 "
               "(decision 45.1).")
# verdict changes each group recorded (decisions 72.1, 74.1, 76.1, 77.3 and the sessions' handoffs)
CHANGES = {"blind s71": 5, "blind s72": 2, "blind s73": 8, "blind s74": 3, "blind s75": 6, "blind s76": 0, "blind s77": 4}
CCO = "CCO"


def state():
    """Everything the files and the record are built from."""
    with redirect_stdout(io.StringIO()):
        p = pc.Pass()
        units, part_of, new_units, new_part_of = fp.final_state(p)
        old_new = dict(p.mods[-1].NEW_UNITS)
    return p, units, part_of, new_units, new_part_of, old_new


def build():
    p, units, part_of, new_units, new_part_of, old_new = state()
    rec = {t: r for t, _, _, r, _ in fp.GROUPS}

    def record_of(c, k):
        tag = new_part_of.get((c, k)) or part_of.get((c, k))
        if tag in rec:
            return rec[tag]
        if (c, k) in new_units or k in p.mods[-1].CRITS:
            return "NEEC_Rescoring_s65.md"
        return "the rescoring record of the part that read it"

    def row_notes(changed):
        return [f"Rescoring pass and blind re-read applied (Sessions 65 and 71 to 77; generator Session 78): {changed} of the 26 "
                "published scores changed; C2.6, C3.6 and C4.6 scored for the first time",
                "Provisional until Report and Paper v2.0; every unit's reading is in the rescoring records "
                "(NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md) and the blind records (NEEC_BlindReview_s71.md to "
                "NEEC_BlindReview_s77.md)."]
    texts, _, vec, summary = ap.build({"units": units, "new_units": new_units, "part_of": part_of, "note": NOTE,
                                       "description": DESCRIPTION, "row_notes": row_notes, "record_of": record_of})
    texts = {OUT[k]: texts[SNAP[k]] for k in SNAP}
    crit = json.load(open(os.path.join(HERE, "criteria.json"), encoding="utf-8"))
    order = [c for d in crit["domains"] for c in d["criteria"]]
    # the changes against the pass's own result (Session 65)
    changes = []
    for tag, sess, _, rf, _ in fp.GROUPS:
        for k, u in sorted({**units, **new_units}.items(), key=lambda kv: (p.order.index(kv[0][0]), order.index(kv[0][1]))):
            tg = new_part_of.get(k) or part_of.get(k)
            old = old_new[k] if k in old_new else p.merged[k]
            if tg == tag and old["verdict"] != u["verdict"]:
                changes.append((tag, sess, k, old["verdict"], u["verdict"]))
    texts[OUT["record"]] = record(p, units, new_units, old_new, vec, summary, changes)
    return texts, p, units, new_units, old_new, vec, summary, changes


def record(p, units, new_units, old_new, vec, summary, changes):
    f1 = pc.f1
    names = p.names
    crit = json.load(open(os.path.join(HERE, "criteria.json"), encoding="utf-8"))
    cname = {c["id"]: c["name"] for c in crit["criteria"]}
    tot26 = p.steps[-1]["total"]
    old = {c: tot26[c] + sum(r["verdict"] for (cc, k), r in old_new.items() if cc == c) for c in p.order}
    oldf = {c: p.steps[-1]["fail"][c] + sum(1 for (cc, k), r in old_new.items() if cc == c and r["verdict"] == 0.0)
            for c in p.order}
    now = {c: summary[c][0] for c in summary}
    nowf = {c: summary[c][1] for c in summary}
    pub = p.steps[0]["total"]
    rk_pub, rk_old, rk_now = pc.ranks(pub), pc.ranks(old), pc.ranks(now)
    groups = fp.load_groups()
    rows = ["| Group | Session | Record | Units read | Verdict changes |", "|---|---:|---|---:|---:|"]
    for (tag, sess, rf, fin) in groups:
        n = sum(1 for ch in changes if ch[0] == tag)
        rows.append(f"| {tag} | {sess} | {rf} | {len(fin)} | {n} |")
    rows.append(f"| all | | | {sum(len(f) for _, _, _, f in groups)} | {len(changes)} |")
    t_groups = "\n".join(rows)
    rows = ["| Group | Entry | Criterion | Part (2.11) or the pass | Final |", "|---|---|---|---:|---:|"]
    for tag, sess, (c, k), a, b in changes:
        rows.append(f"| {tag} | {names[c]} | {k} {cname[k]} | {f1(a)} | {f1(b)} |")
    t_changes = "\n".join(rows)
    rows = ["| Entry | Published, 26 criteria (rank) | After the pass, 29 (rank) | Now, 29 (rank) | Change here | Failures now "
            "| Tier now | Tier after the pass |", "|---|---:|---:|---:|---:|---:|---|---|"]
    for c in sorted(p.order, key=lambda x: (-now[x], p.order.index(x))):
        rows.append(f"| {c} | {f1(pub[c])} ({rk_pub[c]}) | {f1(old[c])} ({rk_old[c]}) | {f1(now[c])} ({rk_now[c]}) | "
                    f"{f1(now[c] - old[c])} | {nowf[c]} | {pc.tier(nowf[c])} | {pc.tier(oldf[c])} |")
    t_standing = "\n".join(rows)
    tier_ch = [c for c in p.order if pc.tier(nowf[c]) != pc.tier(oldf[c])]
    first = [c for c in p.order if now[c] == max(now.values())]
    first_old = [c for c in p.order if old[c] == max(old.values())]
    second = max(now[c] for c in p.order if c not in first)
    cco_ch = [ch for ch in changes if ch[2][0] == CCO]
    cco_flags = sorted(k for (c, k), u in {**units, **new_units}.items() if c == CCO and u.get("flag"))
    flagged = sum(1 for u in {**units, **new_units}.values() if u.get("flag"))
    out = ["# NEEC final application, Session 78 (ledger S61)", "",
           "> Generated by `apply_final_s78.py`; never edit by hand. Provisional until Report and Paper v2.0.", "",
           "## 1. What was applied", "",
           "Seven blind groups (Sessions 71 to 77; decisions 69.1, 69.2; ledger D52, D53) re-read 221 units of the rescoring "
           "pass blind. Each group's final readings (its script's `FINAL`, with Session 74's `EXTRA_FINAL` and Session 75's "
           "`FIRST_FINAL`) replace the pass's reading of the same cell (`final_pass.py`); no cell is read by two groups. The "
           "units of C2.6, C3.6 and C4.6 (Sessions 76 and 77) replace the Session 65 readings of the three new criteria; the "
           "others replace the pass's merged units of the 26 published criteria. Every other cell keeps the score the pass "
           "gave it.", "", t_groups, "",
           "## 2. Verdict changes", "",
           f"{len(changes)} cells change verdict against the pass's own result (the Session 65 files, kept as "
           "`neec_corpus_v2_s65_snapshot.json` and its two companions); every other cell, and every cell whose clause "
           "readings or flags changed without its verdict, keeps its verdict.", "", t_changes, "",
           "## 3. The standing", "",
           "Totals on the 29 criteria; failures are cells at 0.0; tiers by integer failure bands 0-2, 3-5 and 6+ (decision "
           "45.1).", "", t_standing, "",
           "## 4. Tier changes, first place and CCO-PTF-CIP-SZH", "",
           "- Tier changes against the pass's result: " + (", ".join(
               f"{names[c]} ({pc.tier(oldf[c])} to {pc.tier(nowf[c])}, {oldf[c]} to {nowf[c]} failures)" for c in tier_ch)
               or "none") + ".",
           f"- First place: {', '.join(names[c] for c in first)} at {f1(now[first[0]])}"
           + (" alone" if len(first) == 1 else " (shared)") + f", ahead of {f1(second)}; after the pass it was "
           + (("shared by " + " and ".join(names[c] for c in first_old)) if len(first_old) > 1 else names[first_old[0]] + " alone")
           + f" at {f1(old[first_old[0]])}.",
           f"- {names[CCO]}: " + (f"{len(cco_ch)} verdict changes" if cco_ch else "no verdict changes") + f", total {f1(now[CCO])} "
           f"({f1(old[CCO])} after the pass), {nowf[CCO]} failures; its units carrying a flag: " + (", ".join(cco_flags) or "none")
           + ". Decision 57.2 and ledger D38 hold: nothing is applied to it by this generator that the blind groups did not read.",
           f"- Units carrying a flag in the final readings: {flagged} of {len(units) + len(new_units)} units the pass and the blind "
           "groups read; a flag is registered as a close call in the site's blocks and the evidence reports where it names a score "
           "other than the verdict.", ""]
    return "\n".join(out)


def main():
    texts, p, units, new_units, old_new, vec, summary, changes = build()
    if "--check" in sys.argv[1:]:
        ok = True

        def check(cond, text, detail=""):
            nonlocal ok
            print(f"  {'PASS' if cond else 'FAIL'} {text}" + ("" if cond or not detail else f": {detail}"))
            ok = ok and bool(cond)
        for name, t in texts.items():
            good = os.path.isfile(os.path.join(HERE, name)) and open(os.path.join(HERE, name), encoding="utf-8").read() == t
            check(good, f"{name} equals what the generator produces")
        corpus = json.loads(texts[OUT["corpus"]])
        snap = json.load(open(os.path.join(HERE, SNAP["corpus"]), encoding="utf-8"))
        v_now = {e["code"]: e["vector"] for e in corpus["entries"]}
        v_old = {e["code"]: e["vector"] for e in snap["entries"]}
        allu = {**units, **new_units}
        check(all(v_now[c][k] == u["verdict"] for (c, k), u in allu.items()),
              f"the corpus carries the final verdict of each of the {len(allu)} units")
        moved = {(c, k) for c in v_now for k in v_now[c] if v_now[c][k] != v_old[c][k]}
        check(moved == {ch[2] for ch in changes} and len(moved) == len(changes),
              f"the corpus differs from the Session 65 snapshot in exactly the {len(changes)} cells the groups changed")
        per = {t: sum(1 for ch in changes if ch[0] == t) for t in CHANGES}
        check(per == CHANGES, "each group changed the verdicts it recorded: " + ", ".join(f"{t.split()[1]} {n}" for t, n in per.items()))
        rows = {r["system"]: r for r in csv.DictReader(io.StringIO(texts[OUT["csv"]]))}
        check(all(abs(float(rows[p.names[c]]["total_score"]) - sum(v_now[c].values())) < 1e-9
                  and int(rows[p.names[c]]["failures"]) == sum(1 for x in v_now[c].values() if x == 0.0) for c in v_now),
              "each total and failure count in the CSV is the sum of the corpus vector")
        blocks = json.loads(texts[OUT["blocks"]])
        check(all(b["vector"] == v_now[b["code"]] and b["summary"]["total"] == sum(v_now[b["code"]].values()) for b in blocks),
              "each block's vector and total equal the corpus's")
        now = {c: sum(v.values()) for c, v in v_now.items()}
        old = {c: sum(v.values()) for c, v in v_old.items()}
        fails = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_now.items()}
        fails_old = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_old.items()}
        tier_ch = sorted(c for c in now if pc.tier(fails[c]) != pc.tier(fails_old[c]))
        check(tier_ch == ["SWF", "UBI"] and pc.tier(fails["UBI"]) == "Partially Adequate"
              and pc.tier(fails_old["UBI"]) == "Structurally Inadequate" and pc.tier(fails["SWF"]) == "Potentially Adequate"
              and pc.tier(fails_old["SWF"]) == "Partially Adequate",
              "the tier changes are Universal Basic Income's (Structurally to Partially Adequate) and Sovereign Wealth Fund "
              "Statism's (Partially to Potentially Adequate), as Sessions 73 and 75 recorded")
        top = [c for c in now if now[c] == max(now.values())]
        check(top == ["PE"] and abs(now["PE"] - 16.5) < 1e-9 and sorted(now.values())[-2] == 16.0,
              "Participatory Economics is first alone at 16.5, ahead of 16.0, as Sessions 71 and 77 recorded")
        check(v_now[CCO] == v_old[CCO], "CCO-PTF-CIP-SZH's vector is unchanged: no blind group changed one of its verdicts "
                                        "(decisions 57.2, 69.4)")
        check(set(vec) == set(p.order) and all(sorted(v) == sorted(corpus["criteria"]) for v in v_now.values()),
              "23 entries on the 29 criteria")
        print("\nSTAGE 3B APPLICATION CHECKED." if ok else "\nSTAGE 3B APPLICATION: CHECKS FAILED.")
        return 0 if ok else 1
    for name, t in texts.items():
        open(os.path.join(HERE, name), "w", encoding="utf-8").write(t)
        print(f"  wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
