#!/usr/bin/env python3
"""
apply_pass_s65.py -- NEEC rescoring pass, stage 3: the generator that applies the pass (decision 65.4)
=====================================================================================================
Session 65. The pass has read every unit in play (groups 2.1 to 2.10 and the accelerated groups of Session 65) and scored the
69 units of the three new criteria. This script applies it: it takes the published 26-criterion vectors (neec_corpus.json,
untouched, because every part of the pass is computed against them), applies every part's readings in order through the shared
module (pass_common.py), adds the 69 new units, and writes the v2.0 corpus in three new files, never by hand:

  neec_corpus_v2.json       the 23 entries on the 29 criteria of criteria.json
  neec_scores_v2.csv        their totals, domain sums, failures and tiers (integer failure bands 0-2, 3-5, 6+, decision 45.1)
  summary_blocks_v2.json    the site's per-entry blocks: the flagged calls (the pass's, and the published ones that still
                            apply) and the joint readings (as scored, every flagged call resolved up, resolved down)

The files the pass was computed against (neec_corpus.json, neec_scores.csv, summary_blocks_s28.json) are not changed.
site/config.json names the v2 files when scores are published.

Usage: python3 apply_pass_s65.py           write the three files
       python3 apply_pass_s65.py --check   recompute and compare with the files on disk (exit 1 on any difference); also checks
                                           that the vectors equal the pass's final state and the totals equal the record's table
Prints file names and summaries only. Deterministic.
"""
import csv
import io
import json
import os
import sys
from contextlib import redirect_stdout
from decimal import Decimal, ROUND_HALF_UP

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pass_common as pc  # noqa: E402

OUT = {"corpus": "neec_corpus_v2.json", "csv": "neec_scores_v2.csv", "blocks": "summary_blocks_v2.json"}
SESSION_NOTE = ("NEEC v1 scores re-estimated on the v2.0 criteria by the rescoring pass (NEEC_Rescoring_s37.md to "
                "NEEC_Rescoring_s65.md), the three new criteria scored in Session 65, applied by apply_pass_s65.py; provisional "
                "until Report and Paper v2.0")


def pct(total, mx):
    return int((Decimal(str(total)) / Decimal(str(mx)) * 100).quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def build():
    with redirect_stdout(io.StringIO()):
        p = pc.Pass()
    crit = json.load(open(os.path.join(HERE, "criteria.json"), encoding="utf-8"))
    order = [c for d in crit["domains"] for c in d["criteria"]]
    new_units = p.mods[-1].NEW_UNITS
    final26 = p.vsteps[-1]
    vec = {}
    for code in p.order:
        v = {k: final26[code][k] for k in p.cids}
        for (c, k), r in new_units.items():
            if c == code:
                v[k] = r["verdict"]
        assert sorted(v) == sorted(order), code
        vec[code] = {k: v[k] for k in order}
    base = json.load(open(os.path.join(HERE, pc.CORPUS), encoding="utf-8"))
    corpus = {"schema": "neec-corpus/2.0",
              "description": ("The NEEC corpus on the v2.0 criteria (29 criteria in five domains): the published 26-criterion "
                              "vectors with the rescoring pass applied and the three new criteria scored. Generated by "
                              "apply_pass_s65.py from neec_corpus.json and the pass's readings; never edited by hand. Scores: "
                              "1.0 pass, 0.5 partial, 0.0 structural failure; totals, failures and tiers follow by protocol "
                              "section 2, with integer failure bands 0-2, 3-5 and 6+ on the 29 (decision 45.1)."),
              "criteria": order,
              "entries": [{"key": e["key"], "code": e["code"], "display_name": e["display_name"],
                           "scope_class": e["scope_class"], "vector": vec[e["code"]]} for e in base["entries"]]}
    dom = {d["id"]: d["criteria"] for d in crit["domains"]}
    names = {d["id"]: d["name"].lower().replace(" ", "_") for d in crit["domains"]}
    tiers = crit["tiers"]

    def tier_of(f):
        return next(t["name"] for t in tiers if t["failures_min"] <= f <= t["failures_max"])

    header = ["system", "criteria_count", "domain1_max"] + [f"domain{i + 1}_{names[d]}" for i, d in enumerate(dom)] + [
        "total_score", "total_percent", "failures", "adequacy_tier", "revision_note", "notes"]
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    summary = {}
    for e in corpus["entries"]:
        v = e["vector"]
        total = sum(v.values())
        fails = sum(1 for x in v.values() if x == 0.0)
        changed = sum(1 for k in p.cids if v[k] != p.vec[e["code"]][k])
        w.writerow([e["display_name"], len(order), f"{float(crit['structure']['domain_max']['D1']):.1f}"]
                   + [f"{sum(v[c] for c in dom[d]):.1f}" for d in dom]
                   + [f"{total:.1f}", f"{pct(total, len(order))}%", fails, tier_of(fails),
                      f"Rescoring pass applied (Session 65): {changed} of the 26 published scores changed; C2.6, C3.6 and C4.6 "
                      "scored for the first time",
                      "Provisional until Report and Paper v2.0; every unit's reading is in the rescoring records "
                      "(NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md)."])
        summary[e["code"]] = (total, fails, tier_of(fails))
    # blocks
    old = {b["code"]: b for b in json.load(open(os.path.join(HERE, "summary_blocks_s28.json"), encoding="utf-8"))}
    blocks = []
    for e in corpus["entries"]:
        code, v = e["code"], e["vector"]
        b = json.loads(json.dumps(old[code]))
        b["vector"] = v
        b["record"]["scored"] = SESSION_NOTE
        b["record"]["structure"] = "v2.0, 29 criteria"
        sm = {d: sum(v[c] for c in dom[d]) for d in dom}
        total, fails, tier = summary[code]
        b["summary"] = {**sm, "total": total, "failures": fails, "tier": tier}
        flags = []
        for (c, k), r in list(p.merged.items()) + list(new_units.items()):
            if c == code and r.get("flag"):
                f0, f1_ = r["flag"]
                alts = [float(x) for x in f0] if isinstance(f0, (list, tuple)) else [float(f0[:3])]
                alts = [a for a in alts if a != v[k]]
                if alts:
                    text = f1_ if len(f1_) > 12 else (r["note"] or "see the pass record")
                    flags.append({"criterion": k, "scored": v[k], "alternatives": alts, "basis": "stated",
                                  "reading": text[:240], "tracks": None,
                                  "source": {"file": "NEEC_Rescoring_s65.md" if (c, k) in new_units or k in
                                             p.mods[-1].CRITS else "the rescoring record of the part that read it",
                                             "locator": f"{code} {k}", "phrase": "Flag"}})
        for f in old[code]["flags"]:
            if f["criterion"] not in {x["criterion"] for x in flags} and (code, f["criterion"]) not in p.merged \
                    and f["criterion"] in v and f["scored"] == v[f["criterion"]]:
                flags.append(f)
        flags.sort(key=lambda f: order.index(f["criterion"]))
        b["flags"] = flags

        def result(resolve):
            vv = dict(v)
            vv.update(resolve)
            t = sum(vv.values())
            fl = sum(1 for x in vv.values() if x == 0.0)
            return {"total": t, "failures": fl, "tier": tier_of(fl)}
        readings = [{"id": "scored", "label": "as scored", "basis": "scored", "resolve": {}, "result": result({})}]
        up = {f["criterion"]: max(f["alternatives"] + [f["scored"]]) for f in flags}
        dn = {f["criterion"]: min(f["alternatives"] + [f["scored"]]) for f in flags}
        if any(up[k] != v[k] for k in up):
            readings.append({"id": "up", "label": "every flagged call resolved upward", "basis": "extremes",
                             "resolve": {k: x for k, x in up.items() if x != v[k]}, "result": result(up)})
        if any(dn[k] != v[k] for k in dn):
            readings.append({"id": "down", "label": "every flagged call resolved downward", "basis": "extremes",
                             "resolve": {k: x for k, x in dn.items() if x != v[k]}, "result": result(dn)})
        b["joint_readings"] = readings
        blocks.append(b)
    texts = {OUT["corpus"]: json.dumps(corpus, indent=1, ensure_ascii=False) + "\n", OUT["csv"]: buf.getvalue(),
             OUT["blocks"]: json.dumps(blocks, indent=1, ensure_ascii=False) + "\n"}
    return texts, p, vec, summary


def main():
    texts, p, vec, summary = build()
    if "--check" in sys.argv[1:]:
        ok = True
        for name, t in texts.items():
            good = os.path.isfile(os.path.join(HERE, name)) and open(os.path.join(HERE, name), encoding="utf-8").read() == t
            ok &= good
            print(f"  {'PASS' if good else 'FAIL'} {name} equals what the pass produces")
        good = all(vec[c][k] == p.vsteps[-1][c][k] for c in vec for k in p.cids)
        ok &= good
        print(f"  {'PASS' if good else 'FAIL'} the 26 published criteria's final scores are the pass's final state")
        tot = {c: summary[c][0] for c in summary}
        good = all(abs(tot[c] - (sum(p.steps[-1]["total"][c] for _ in [0]) + sum(
            r["verdict"] for (cc, k), r in p.mods[-1].NEW_UNITS.items() if cc == c))) < 1e-9 for c in tot)
        ok &= good
        print(f"  {'PASS' if good else 'FAIL'} each total on the 29 is the pass's total on the 26 plus the entry's three new units")
        rec = open(os.path.join(HERE, "NEEC_Rescoring_s65.md"), encoding="utf-8").read()
        rk = pc.ranks(tot)
        rows = all(f"| {c} | {pc.f1(tot[c])} ({rk[c]}) |" in rec for c in tot)
        ok &= rows
        print(f"  {'PASS' if rows else 'FAIL'} NEEC_Rescoring_s65.md's table on the 29 shows these totals and ranks")
        print("\nSTAGE 3 APPLICATION CHECKED." if ok else "\nSTAGE 3 APPLICATION: CHECKS FAILED.")
        return 0 if ok else 1
    for name, t in texts.items():
        open(os.path.join(HERE, name), "w", encoding="utf-8").write(t)
        print(f"  wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
