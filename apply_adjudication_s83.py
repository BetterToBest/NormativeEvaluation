#!/usr/bin/env python3
"""
apply_adjudication_s83.py -- NEEC: the generator that applies the adjudication of the outside review (Session 83, ledger S65)
===========================================================================================================================
The outside review's reader disagreed with NEEC's verdict on 177 of 667 units (compare_outside.py). Session 83 adjudicated
each on the sources (adjudicate_s83.py; the record NEEC_Adjudication_s83.md). final_pass.adjudicated_state() lays the
adjudication's units over the owner's decisions of Session 79; this script writes, never by hand:

  neec_corpus_v2.json         the 23 entries on the 29 criteria, with the adjudication applied
  neec_scores_v2.csv          their totals, domain sums, failures and tiers
  summary_blocks_v2.json      the site's per-entry blocks (each changed or flagged unit's alternative is its close call)
  NEEC_Adjudication_s83.md    the generated tables only, between the record's '<!-- generated:NAME -->' and
                              '<!-- /generated -->' markers: the 177 outcomes, the changes, the standing, the summary

The Session 79 state is kept as neec_corpus_v2_s79_snapshot.json and its two companions (apply_owner_s79.py writes them);
compare_outside.py and outside_kit.py read those, the files the pre-registration and the kit name.

Usage: python3 apply_adjudication_s83.py           write the three files and the record's generated tables
       python3 apply_adjudication_s83.py --check   recompute and compare with the files on disk (exit 1 on any difference);
                                                   also recomputes the 177 disagreements from the run's results and checks
                                                   each outcome, the changed cells, the owner's cells, totals and standing
Prints file names and summaries only. Deterministic.
"""
import csv
import gzip
import io
import json
import os
import re
import sys
from contextlib import redirect_stdout

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apply_pass_s65 as ap  # noqa: E402
import final_pass as fp  # noqa: E402
import pass_common as pc  # noqa: E402

OUT = {"corpus": "neec_corpus_v2.json", "csv": "neec_scores_v2.csv", "blocks": "summary_blocks_v2.json"}
SNAP = {"corpus": "neec_corpus_v2_s79_snapshot.json", "csv": "neec_scores_v2_s79_snapshot.csv",
        "blocks": "summary_blocks_v2_s79_snapshot.json"}
RECORD = "NEEC_Adjudication_s83.md"
RUN = os.path.join(HERE, "outside_review_r1")
NOTE = ("NEEC v1 scores re-estimated on the v2.0 criteria by the rescoring pass (NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), "
        "the three new criteria scored in Session 65, re-read blind in Sessions 71 to 77 (NEEC_BlindReview_s71.md to "
        "NEEC_BlindReview_s77.md), with the owner's decisions 79.1 to 79.4 (NEEC_OwnerDecisions_s79.md) and the adjudication "
        "of the outside review (NEEC_Adjudication_s83.md), applied by apply_adjudication_s83.py; provisional until Report and "
        "Paper v2.0")
DESCRIPTION = ("The NEEC corpus on the v2.0 criteria (29 criteria in five domains): the published 26-criterion vectors with the "
               "rescoring pass applied, the three new criteria scored, the blind re-read's final readings (Sessions 71 to 77), "
               "the owner's decisions 79.1 to 79.4 (Session 79) and the adjudication of the outside review (Session 83) laid "
               "over them. Generated by apply_adjudication_s83.py; never edited by hand. Scores: 1.0 pass, 0.5 partial, 0.0 "
               "structural failure; totals, failures and tiers follow by protocol section 2, with integer failure bands 0-2, "
               "3-5 and 6+ on the 29 (decision 45.1).")
GEN = re.compile(r"(<!-- generated:(\w+) -->\n)(.*?)(<!-- /generated -->)", re.S)


def state():
    with redirect_stdout(io.StringIO()):
        p = pc.Pass()
        units, part_of, new_units, new_part_of, final_part_of, owner_part_of = fp.adjudicated_state(p)
        adj = pc.load("adjudicate_s83", "adjudicate_s83.py")
        ow = pc.load("owner_s79", "owner_s79.py")
    return p, units, part_of, new_units, new_part_of, owner_part_of, adj, ow


def build():
    p, units, part_of, new_units, new_part_of, owner_part_of, adj, ow = state()
    rec = {t: r for t, _, _, r, _ in fp.GROUPS}
    rec[ow.TAG] = ow.RECORD
    rec[adj.TAG] = adj.RECORD

    def record_of(c, k):
        tag = new_part_of.get((c, k)) or part_of.get((c, k))
        if tag in rec:
            return rec[tag]
        if (c, k) in new_units or k in p.mods[-1].CRITS:
            return "NEEC_Rescoring_s65.md"
        return "the rescoring record of the part that read it"

    def row_notes(changed):
        return [f"Rescoring pass, blind re-read, the owner's decisions and the adjudication of the outside review applied "
                f"(Sessions 65, 71 to 77, 79 and 83; generators Sessions 78, 79 and 83): {changed} of the 26 published scores "
                f"changed; C2.6, C3.6 and C4.6 scored for the first time",
                "Provisional until Report and Paper v2.0; every unit's reading is in the rescoring records "
                "(NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), the blind records (NEEC_BlindReview_s71.md to "
                "NEEC_BlindReview_s77.md), NEEC_OwnerDecisions_s79.md and NEEC_Adjudication_s83.md."]
    texts, _, vec, summary = ap.build({"units": units, "new_units": new_units, "part_of": part_of, "note": NOTE,
                                       "description": DESCRIPTION, "row_notes": row_notes, "record_of": record_of})
    texts = {OUT[k]: texts[ap.OUT[k]] for k in ("corpus", "csv", "blocks")}
    snap = json.load(open(os.path.join(HERE, SNAP["corpus"]), encoding="utf-8"))
    v_old = {e["code"]: e["vector"] for e in snap["entries"]}
    return texts, p, adj, ow, units, new_units, vec, v_old


def tables(p, adj, vec, v_old):
    """The record's generated tables, by name."""
    f1 = pc.f1
    names = p.names
    crit = json.load(open(os.path.join(HERE, "criteria.json"), encoding="utf-8"))
    order = [c for d in crit["domains"] for c in d["criteria"]]
    cname = {c["id"]: c["name"] for c in crit["criteria"]}
    units = {u["unit"]: u for u in kit_units()}
    O = adj.OUTCOMES
    keys = sorted(O, key=lambda k: (order.index(k[1]), p.order.index(k[0])))
    out = {}
    rows = ["| Criterion | Entry | Group | NEEC | Reader | Outcome | Now | Reason |", "|---|---|---:|---:|---:|---|---:|---|"]
    for c, k in keys:
        o = O[(c, k)]
        g = units[f"{c}|{k}"]["group"]
        rows.append(f"| {k} | {names[c]} | {g} | {f1(o['neec'])} | {f1(o['reader'])} | {o['outcome']} | {f1(o['stands'])} | "
                    f"{o['why']} |")
    out["outcomes"] = "\n".join(rows)
    rows = ["| Criterion | Entry | Outcome | Before | After | Failures before / after | Close call kept |",
            "|---|---|---|---:|---:|---|---|"]
    for c, k in keys:
        o = O[(c, k)]
        if o["outcome"] in ("adopt", "third"):
            u = adj.UNITS[(c, k)]
            fb = sum(1 for x in v_old[c].values() if x == 0.0)
            fa = sum(1 for x in vec[c].values() if x == 0.0)
            fl = f"toward {f1(u['flag'][0][0])}" if u["flag"] else "none (reach)"
            rows.append(f"| {k} {cname[k]} | {names[c]} | {o['outcome']} | {f1(o['neec'])} | {f1(o['stands'])} | {fb} / {fa} | {fl} |")
    out["changes"] = "\n".join(rows)
    rows = ["| Criterion | Entry | Kind | Verdict | What the unit now carries |", "|---|---|---|---:|---|"]
    for (c, k) in sorted(adj.UNITS, key=lambda k: (order.index(k[1]), p.order.index(k[0]))):
        u = adj.UNITS[(c, k)]
        if u["kind"] == "change":
            continue
        what = (f"a close call toward {f1(u['flag'][0][0])}: {u['flag'][1]}" if u["flag"] else "") if u["kind"] == "flag" \
            else u["note"] + (f"; close call toward {f1(u['flag'][0][0])}" if u["flag"] else "")
        rows.append(f"| {k} | {names[c]} | {u['kind']} | {f1(u['verdict'])} | {what} |")
    out["revisions"] = "\n".join(rows)
    now = {c: sum(v.values()) for c, v in vec.items()}
    old = {c: sum(v.values()) for c, v in v_old.items()}
    fn = {c: sum(1 for x in v.values() if x == 0.0) for c, v in vec.items()}
    fo = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_old.items()}
    ov = owner_vectors(vec, adj)
    oa = {c: sum(v.values()) for c, v in ov.items()}
    rk_o, rk_n, rk_a = pc.ranks(old), pc.ranks(now), pc.ranks(oa)
    rows = ["| Entry | Session 79 (rank) | Adjudicated (rank) | Change | Failures | Tier | With the four owner items (rank) |",
            "|---|---:|---:|---:|---:|---|---:|"]
    for c in sorted(p.order, key=lambda x: (-now[x], p.order.index(x))):
        tier = pc.tier(fn[c]) + ("" if pc.tier(fn[c]) == pc.tier(fo[c]) else f" (was {pc.tier(fo[c])})")
        rows.append(f"| {names[c]} | {f1(old[c])} ({rk_o[c]}) | {f1(now[c])} ({rk_n[c]}) | {f1(now[c] - old[c])} | "
                    f"{fo[c]} to {fn[c]} | {tier} | {f1(oa[c])} ({rk_a[c]}) |")
    out["standing"] = "\n".join(rows)
    cnt = {x: sum(1 for o in O.values() if o["outcome"] == x) for x in ("hold", "adopt", "third", "owner", "stands")}
    kinds = {x: sum(1 for u in adj.UNITS.values() if u["kind"] == x) for x in ("change", "revision", "flag")}
    first = [c for c in p.order if now[c] == max(now.values())]
    second = max(now[c] for c in p.order if c not in first)
    out["summary"] = (f"{len(O)} disagreements: {cnt['hold']} hold NEEC's verdict, {cnt['adopt']} adopt the reader's, "
                      f"{cnt['third']} reach a third reading, {cnt['owner']} go to the owner and {cnt['stands']} are owner-decided "
                      f"cells that stand. The layer writes {len(adj.UNITS)} units: {kinds['change']} verdict changes, "
                      f"{kinds['revision']} clause revisions and {kinds['flag']} new close calls on held verdicts. First "
                      f"place: {', '.join(names[c] for c in first)} at {f1(now[first[0]])}, ahead of {f1(second)}; tier "
                      f"changes: {', '.join(names[c] for c in p.order if pc.tier(fn[c]) != pc.tier(fo[c])) or 'none'}.")
    return out


def owner_vectors(vec, adj):
    """The vectors with the four owner items applied as the adjudication reads them (never written)."""
    ov = {c: dict(v) for c, v in vec.items()}
    for (c, k), it in adj.OWNER.items():
        ov[c][k] = it["proposed"]
    return ov


def kit_units():
    return [json.loads(ln) for ln in open(os.path.join(RUN, "kit_units.jsonl"), encoding="utf-8") if ln.strip()]


def disagreements(v_old):
    """{(code, criterion): (NEEC, reader)} recomputed from the run's reader results and the Session 79 corpus."""
    first = {u["unit"]: u for u in kit_units() if u["group"] != 2.5}
    rd = {}
    with gzip.open(os.path.join(RUN, "results", "reader.jsonl.gz"), "rt", encoding="utf-8") as f:
        for ln in f:
            r = json.loads(ln)
            if r.get("status") == "ok" and r["unit"] in first and (r.get("final") or {}).get("verdict") in (0.0, 0.5, 1.0):
                rd[r["unit"]] = r["final"]["verdict"]
    out = {}
    for un, u in first.items():
        if un in rd and rd[un] != v_old[u["code"]][u["cid"]]:
            out[(u["code"], u["cid"])] = (v_old[u["code"]][u["cid"]], rd[un])
    return out, len(rd)


def record_text(gen):
    path = os.path.join(HERE, RECORD)
    if not os.path.isfile(path):
        return None, None
    old = open(path, encoding="utf-8").read()
    new = GEN.sub(lambda m: m.group(1) + gen[m.group(2)] + "\n" + m.group(4), old)
    return old, new


def main():
    texts, p, adj, ow, units, new_units, vec, v_old = build()
    gen = tables(p, adj, vec, v_old)
    old_rec, new_rec = record_text(gen)
    if "--check" in sys.argv[1:]:
        ok = True

        def check(cond, text, detail=""):
            nonlocal ok
            print(f"  {'PASS' if cond else 'FAIL'} {text}" + ("" if cond or not detail else f": {detail}"))
            ok = ok and bool(cond)
        for name, t in texts.items():
            good = os.path.isfile(os.path.join(HERE, name)) and open(os.path.join(HERE, name), encoding="utf-8").read() == t
            check(good, f"{name} equals what the generator produces")
        names_in = {m.group(2) for m in GEN.finditer(old_rec or "")}
        check(old_rec is not None and old_rec == new_rec and names_in == set(gen),
              f"{RECORD} carries every generated table ({', '.join(sorted(gen))}) as the generator produces it")
        corpus = json.loads(open(os.path.join(HERE, OUT["corpus"]), encoding="utf-8").read())
        v_now = {e["code"]: e["vector"] for e in corpus["entries"]}
        allu = {**units, **new_units}
        check(all(v_now[c][k] == u["verdict"] for (c, k), u in allu.items()),
              f"the corpus carries the verdict of each of the {len(allu)} units")
        dis, n = disagreements(v_old)
        O = adj.OUTCOMES
        check(n == 667 and len(dis) == 177 and set(dis) == set(O)
              and all(dis[k] == (O[k]["neec"], O[k]["reader"]) for k in O),
              f"the run's reader results ({n} first readings) against the Session 79 corpus give {len(dis)} disagreements, "
              "each with its outcome and the verdicts the outcome names")
        moved = {(c, k) for c in v_now for k in v_now[c] if v_now[c][k] != v_old[c][k]}
        changed = {k for k, o in O.items() if o["outcome"] in ("adopt", "third")}
        check(moved == changed and all(v_now[c][k] == O[(c, k)]["stands"] for c, k in moved)
              and {k for k, u in adj.UNITS.items() if u["kind"] == "change"} == changed,
              f"the corpus differs from the Session 79 snapshot in exactly the {len(changed)} cells the adjudication changes, "
              "each to the verdict its outcome names")
        owner_cells = set(ow.CHANGES) | {("CCO", "C3.2")}
        check(not any(c == "CCO" for c, _ in moved) and not (moved & owner_cells)
              and all(v_now[c][k] == v_old[c][k] for c, k in adj.OWNER),
              "no CCO-PTF-CIP-SZH cell and no owner-decided cell changes (decision 57.2); the four owner items are not applied")
        check(all(O[k]["stands"] == O[k]["neec"] for k in O if O[k]["outcome"] in ("hold", "owner", "stands")),
              "every hold, owner item and standing owner cell keeps NEEC's verdict")
        rows = {r["system"]: r for r in csv.DictReader(io.StringIO(texts[OUT["csv"]]))}
        check(all(abs(float(rows[p.names[c]]["total_score"]) - sum(v_now[c].values())) < 1e-9
                  and int(rows[p.names[c]]["failures"]) == sum(1 for x in v_now[c].values() if x == 0.0) for c in v_now),
              "each total and failure count in the CSV is the sum of the corpus vector")
        blocks = json.loads(texts[OUT["blocks"]])
        flagged = {(b["code"], f["criterion"]): f["alternatives"] for b in blocks for f in b["flags"]}
        check(all(b["vector"] == v_now[b["code"]] and b["summary"]["total"] == sum(v_now[b["code"]].values()) for b in blocks)
              and all(flagged.get(k) == [u["flag"][0][0]] for k, u in adj.UNITS.items() if u["flag"]),
              "each block's vector and total equal the corpus's, and each adjudicated unit with a flag is a close call "
              "toward its alternative")
        now = {c: sum(v.values()) for c, v in v_now.items()}
        fails = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_now.items()}
        fails_old = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_old.items()}
        top = sorted(now, key=lambda c: -now[c])
        check(top[0] == "CCO" and abs(now["CCO"] - 17.5) < 1e-9 and top[1] == "PE" and abs(now["PE"] - 16.5) < 1e-9
              and now[top[2]] < 16.5,
              "CCO-PTF-CIP-SZH is first alone at 17.5, Participatory Economics second at 16.5")
        check(all(pc.tier(fails[c]) == pc.tier(fails_old[c]) for c in now), "no tier changes")
        oa = {c: sum(v.values()) for c, v in owner_vectors(v_now, adj).items()}
        check(abs(oa["CCO"] - 16.5) < 1e-9 and abs(oa["PE"] - 16.0) < 1e-9 and max(oa, key=lambda c: oa[c]) == "CCO",
              "with the four owner items applied as adjudicated, CCO-PTF-CIP-SZH stands at 16.5 and Participatory "
              "Economics at 16.0")
        print("\nADJUDICATION OF SESSION 83: APPLICATION CHECKED." if ok else "\nADJUDICATION OF SESSION 83: CHECKS FAILED.")
        return 0 if ok else 1
    for name, t in texts.items():
        open(os.path.join(HERE, name), "w", encoding="utf-8").write(t)
        print(f"  wrote {name}")
    if new_rec is not None and new_rec != old_rec:
        open(os.path.join(HERE, RECORD), "w", encoding="utf-8").write(new_rec)
        print(f"  wrote the generated tables of {RECORD}")
    print("  " + gen["summary"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
