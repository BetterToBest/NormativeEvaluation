#!/usr/bin/env python3
"""
apply_owner_s79.py -- NEEC: the generator that applies the owner's decisions 79.1 to 79.4 (Session 79)
=====================================================================================================
Session 78 applied the blind re-read (apply_final_s78.py). The owner then decided four changes (owner_s79.py: three
CCO-PTF-CIP-SZH units, and a rule for C3.4's clause 4 that reaches Integral, Participatory Economics, Degrowth Economics and
Ostrom-Style Commons Governance). final_pass.owner_state() lays them over the final readings; this script writes, never by hand:

  neec_corpus_v2.json         the 23 entries on the 29 criteria, with the final readings and the owner's layer
  neec_scores_v2.csv          their totals, domain sums, failures and tiers
  summary_blocks_v2.json      the site's per-entry blocks (each revised unit's prior reading is its flag)
  NEEC_OwnerDecisions_s79.md  the record: the decisions and their reasons, the consistency audit, the seven changes, the
                              standing with and without the owner's decisions, first place and tiers

The Session 78 state is kept as neec_corpus_v2_s78_snapshot.json and its two companions (apply_final_s78.py writes them).

Usage: python3 apply_owner_s79.py           write the four files
       python3 apply_owner_s79.py --check   recompute and compare with the files on disk (exit 1 on any difference); also checks
                                            the corpus against every unit, the seven changes against the Session 78 snapshot,
                                            the tiers, first place and the standing without the owner's decisions
Prints file names and summaries only. Deterministic.
"""
import csv
import io
import json
import os
import sys
from contextlib import redirect_stdout

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import apply_pass_s65 as ap  # noqa: E402
import apply_final_s78 as af  # noqa: E402
import final_pass as fp  # noqa: E402
import pass_common as pc  # noqa: E402

OUT = {"corpus": "neec_corpus_v2.json", "csv": "neec_scores_v2.csv", "blocks": "summary_blocks_v2.json",
       "record": "NEEC_OwnerDecisions_s79.md"}
SNAP = dict(af.OUT)  # the Session 78 state
NOTE = ("NEEC v1 scores re-estimated on the v2.0 criteria by the rescoring pass (NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), "
        "the three new criteria scored in Session 65, re-read blind in Sessions 71 to 77 (NEEC_BlindReview_s71.md to "
        "NEEC_BlindReview_s77.md), with the owner's decisions 79.1 to 79.4 (NEEC_OwnerDecisions_s79.md), applied by "
        "apply_owner_s79.py; provisional until the outside review and Report and Paper v2.0")
DESCRIPTION = ("The NEEC corpus on the v2.0 criteria (29 criteria in five domains): the published 26-criterion vectors with the "
               "rescoring pass applied, the three new criteria scored, the blind re-read's final readings (Sessions 71 to 77) "
               "and the owner's decisions 79.1 to 79.4 (Session 79) laid over them. Generated by apply_owner_s79.py; never "
               "edited by hand. Scores: 1.0 pass, 0.5 partial, 0.0 structural failure; totals, failures and tiers follow by "
               "protocol section 2, with integer failure bands 0-2, 3-5 and 6+ on the 29 (decision 45.1).")
EXPECTED = {("CCO", "C1.2a"), ("CCO", "C2.5"), ("CCO", "C3.4"), ("INT", "C3.4"), ("PE", "C3.4"), ("DG", "C3.4"), ("OS", "C3.4")}


def state():
    with redirect_stdout(io.StringIO()):
        p = pc.Pass()
        units, part_of, new_units, new_part_of, final_part_of = fp.owner_state(p)
        ow = pc.load("owner_s79", "owner_s79.py")
    return p, units, part_of, new_units, new_part_of, final_part_of, ow


def build():
    p, units, part_of, new_units, new_part_of, final_part_of, ow = state()
    rec = {t: r for t, _, _, r, _ in fp.GROUPS}
    rec[ow.TAG] = ow.RECORD

    def record_of(c, k):
        tag = new_part_of.get((c, k)) or part_of.get((c, k))
        if tag in rec:
            return rec[tag]
        if (c, k) in new_units or k in p.mods[-1].CRITS:
            return "NEEC_Rescoring_s65.md"
        return "the rescoring record of the part that read it"

    def row_notes(changed):
        return [f"Rescoring pass, blind re-read and the owner's decisions applied (Sessions 65, 71 to 77 and 79; generators "
                f"Sessions 78 and 79): {changed} of the 26 published scores changed; C2.6, C3.6 and C4.6 scored for the first time",
                "Provisional until the outside review and Report and Paper v2.0; every unit's reading is in the rescoring records "
                "(NEEC_Rescoring_s37.md to NEEC_Rescoring_s65.md), the blind records (NEEC_BlindReview_s71.md to "
                "NEEC_BlindReview_s77.md) and NEEC_OwnerDecisions_s79.md."]
    texts, _, vec, summary = ap.build({"units": units, "new_units": new_units, "part_of": part_of, "note": NOTE,
                                       "description": DESCRIPTION, "row_notes": row_notes, "record_of": record_of})
    texts = {OUT[k]: texts[ap.OUT[k]] for k in ("corpus", "csv", "blocks")}
    snap = json.load(open(os.path.join(HERE, SNAP["corpus"]), encoding="utf-8"))
    v_old = {e["code"]: e["vector"] for e in snap["entries"]}
    texts[OUT["record"]] = record(p, ow, units, new_units, final_part_of, v_old, vec, summary)
    return texts, p, ow, units, new_units, vec, summary, v_old


def record(p, ow, units, new_units, final_part_of, v_old, vec, summary):
    f1 = pc.f1
    names = p.names
    crit = json.load(open(os.path.join(HERE, "criteria.json"), encoding="utf-8"))
    cname = {c["id"]: c["name"] for c in crit["criteria"]}
    allu = {**units, **new_units}
    now = {c: summary[c][0] for c in summary}
    nowf = {c: summary[c][1] for c in summary}
    old = {c: sum(v_old[c].values()) for c in v_old}
    oldf = {c: sum(1 for x in v_old[c].values() if x == 0.0) for c in v_old}
    rk_old, rk_now = pc.ranks(old), pc.ranks(now)
    dec = [f"### {d} ({kind}) {title}\n\n{text}" for d, kind, title, text in ow.DECISIONS]
    rows = ["| Decision | Entry | Criterion | Clause re-read | Read before by | Before | Now |", "|---|---|---|---:|---|---:|---:|"]
    for (c, k), ch in ow.CHANGES.items():
        rows.append(f"| {ch['decision']} | {names[c]} | {k} {cname[k]} | {ch['clause']} | {final_part_of[(c, k)]} | "
                    f"{f1(v_old[c][k])} | {f1(allu[(c, k)]['verdict'])} |")
    t_changes = "\n".join(rows)
    rows = ["| Entry | Without the owner's decisions of Session 79 (rank) | With them (rank) | Change | Failures | Tier |",
            "|---|---:|---:|---:|---:|---|"]
    for c in sorted(p.order, key=lambda x: (-now[x], p.order.index(x))):
        rows.append(f"| {names[c]} | {f1(old[c])} ({rk_old[c]}) | {f1(now[c])} ({rk_now[c]}) | {f1(now[c] - old[c])} | "
                    f"{nowf[c]} | {pc.tier(nowf[c])} |")
    t_standing = "\n".join(rows)
    tier_ch = [c for c in p.order if pc.tier(nowf[c]) != pc.tier(oldf[c])]
    first = [c for c in p.order if now[c] == max(now.values())]
    first_old = [c for c in p.order if old[c] == max(old.values())]
    second = max(now[c] for c in p.order if c not in first)
    # without any owner decision on CCO-PTF-CIP-SZH (58.1 as well as 79.1 to 79.3): its standing on the readings alone
    cco_owner = sum(1 for (c, k) in ow.CHANGES if c == "CCO") * 0.5 + 0.5
    out = ["# NEEC: the owner's decisions of Session 79", "",
           "> Generated by `apply_owner_s79.py` from `owner_s79.py`; never edit by hand. Provisional until the outside review "
           "and Report and Paper v2.0.", "",
           "## 1. The decisions", "",
           f"Decision 57.2 reserves CCO-PTF-CIP-SZH's score changes to the owner, who designed it and co-authors NEEC. The owner "
           f"waited until every reading was in (decision 58.2), then on {ow.DATE} asked that three of its 0.5s be reconsidered "
           "(C1.2a, C2.5, C3.4) and that Integral's C3.4 be raised with CCO-PTF-CIP-SZH's. The reconsideration tested each "
           "argument against the records and applied each reading to every entry. The owner then decided to apply the three "
           "now (not to hold them for the outside review) and to adopt the C3.4 rule for every entry it reaches. Each revised "
           "unit re-reads one clause and carries the others from its final reading; its prior reading stays as its flag, so "
           "the site and the evidence reports show it as a close call.", ""] + [x + "\n" for x in dec] + [
           "## 2. The seven changes", "",
           "Against the Session 78 state (`neec_corpus_v2_s78_snapshot.json`). No other cell changes.", "", t_changes, "",
           "## 3. The standing, with and without the owner's decisions of Session 79", "", t_standing, "",
           "## 4. First place, tiers and disclosure", "",
           f"- First place: {', '.join(names[c] for c in first)} at {f1(now[first[0]])}"
           + (" alone" if len(first) == 1 else " (shared)") + f", ahead of {f1(second)}; without these decisions "
           + (("shared by " + " and ".join(names[c] for c in first_old)) if len(first_old) > 1 else names[first_old[0]] + " alone")
           + f" at {f1(old[first_old[0]])}.",
           "- Tier changes: " + (", ".join(names[c] for c in tier_ch) or "none (a tier depends on failures only, and no "
                                 "decision moves a 0.0)") + ".",
           f"- {names['CCO']} carries {len([1 for (c, _) in ow.CHANGES if c == 'CCO']) + 1} owner decisions in all (58.1 on "
           f"C3.2, and 79.1 to 79.3): {f1(cco_owner)} of its {f1(now['CCO'])}. On the readings alone it would stand at "
           f"{f1(now['CCO'] - cco_owner)}. Report and Paper v2.0 state both figures, and the outside review (decision 79.6) "
           "reads every one of its units blind.",
           f"- Decision 79.4 raises four entries that are not the owner's design; with it, Participatory Economics stands at "
           f"{f1(now['PE'])}.", ""]
    return "\n".join(out)


def main():
    texts, p, ow, units, new_units, vec, summary, v_old = build()
    if "--check" in sys.argv[1:]:
        ok = True

        def check(cond, text, detail=""):
            nonlocal ok
            print(f"  {'PASS' if cond else 'FAIL'} {text}" + ("" if cond or not detail else f": {detail}"))
            ok = ok and bool(cond)
        for name, t in texts.items():
            good = os.path.isfile(os.path.join(HERE, name)) and open(os.path.join(HERE, name), encoding="utf-8").read() == t
            check(good, f"{name} equals what the generator produces")
        corpus = json.loads(open(os.path.join(HERE, OUT["corpus"]), encoding="utf-8").read())
        v_now = {e["code"]: e["vector"] for e in corpus["entries"]}
        allu = {**units, **new_units}
        check(all(v_now[c][k] == u["verdict"] for (c, k), u in allu.items()),
              f"the corpus carries the verdict of each of the {len(allu)} units")
        moved = {(c, k) for c in v_now for k in v_now[c] if v_now[c][k] != v_old[c][k]}
        check(moved == EXPECTED == set(ow.CHANGES) and all(v_old[c][k] == 0.5 and v_now[c][k] == 1.0 for c, k in moved),
              "the corpus differs from the Session 78 snapshot in exactly the seven cells of decisions 79.1 to 79.4, each "
              "0.5 to 1.0")
        rows = {r["system"]: r for r in csv.DictReader(io.StringIO(texts[OUT["csv"]]))}
        check(all(abs(float(rows[p.names[c]]["total_score"]) - sum(v_now[c].values())) < 1e-9
                  and int(rows[p.names[c]]["failures"]) == sum(1 for x in v_now[c].values() if x == 0.0) for c in v_now),
              "each total and failure count in the CSV is the sum of the corpus vector")
        blocks = json.loads(texts[OUT["blocks"]])
        check(all(b["vector"] == v_now[b["code"]] and b["summary"]["total"] == sum(v_now[b["code"]].values()) for b in blocks),
              "each block's vector and total equal the corpus's")
        flagged = {(b["code"], f["criterion"]) for b in blocks for f in b["flags"] if 0.5 in f["alternatives"]}
        check(EXPECTED <= flagged, "each of the seven revised cells is a close call toward 0.5 in the site's blocks")
        now = {c: sum(v.values()) for c, v in v_now.items()}
        old = {c: sum(v.values()) for c, v in v_old.items()}
        fails = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_now.items()}
        fails_old = {c: sum(1 for x in v.values() if x == 0.0) for c, v in v_old.items()}
        check(fails == fails_old, "no failure count changes, so no tier changes")
        top = sorted(now, key=lambda c: -now[c])
        check(top[0] == "CCO" and abs(now["CCO"] - 17.5) < 1e-9 and top[1] == "PE" and abs(now["PE"] - 17.0) < 1e-9
              and now[top[2]] < 17.0,
              "CCO-PTF-CIP-SZH is first alone at 17.5, Participatory Economics second at 17.0")
        check(max(old, key=lambda c: old[c]) == "PE" and abs(old["PE"] - 16.5) < 1e-9 and abs(old["CCO"] - 16.0) < 1e-9,
              "without the owner's decisions of Session 79, Participatory Economics is first at 16.5 and CCO-PTF-CIP-SZH 16.0")
        check(set(vec) == set(p.order) and all(sorted(v) == sorted(corpus["criteria"]) for v in v_now.values()),
              "23 entries on the 29 criteria")
        print("\nOWNER DECISIONS OF SESSION 79: APPLICATION CHECKED." if ok else "\nOWNER DECISIONS OF SESSION 79: CHECKS FAILED.")
        return 0 if ok else 1
    for name, t in texts.items():
        open(os.path.join(HERE, name), "w", encoding="utf-8").write(t)
        print(f"  wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
