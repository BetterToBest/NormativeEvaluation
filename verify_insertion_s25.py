def corrupt_vector(text):
    node = [n for n in ast.parse(text).body if isinstance(n, ast.Assign)
            and any(getattr(t, "id", None) == "OSTROM" for t in n.targets)][0]
    lines = text.split("\n")
    seg = "\n".join(lines[node.lineno - 1:node.end_lineno])
    bad = re.sub(r"""(['"])C5\.5\1: 1\.0""", lambda m: f"{m.group(1)}C5.5{m.group(1)}: 0.5", seg, count=1)
    return text.replace(seg, bad, 1)


