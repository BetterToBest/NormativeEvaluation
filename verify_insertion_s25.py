def run_generator(corrupt=None):
    with tempfile.TemporaryDirectory() as tmp:
        src, out = os.path.join(tmp, "src"), os.path.join(tmp, "out")
        os.makedirs(src)
        for name in GEN_INPUTS:
            shutil.copy(path(name), src)
        if corrupt:
            name, fn = corrupt
            p = os.path.join(src, name)
            with open(p, encoding="utf-8") as f:
                text = f.read()
            new = fn(text)
            assert new != text, f"negative test did not change {name}"
            with open(p, "w", encoding="utf-8") as f:
                f.write(new)
        proc = subprocess.run([sys.executable, GEN, src, out], cwd=src, capture_output=True)
        produced = {n: open(os.path.join(out, n), "rb").read() for n in (CANON, BUILDER)
                    if os.path.isfile(os.path.join(out, n))}
        return proc, produced


