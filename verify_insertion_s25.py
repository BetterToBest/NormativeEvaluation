def module_literal(text, var):
    hits = [ast.literal_eval(n.value) for n in ast.parse(text).body if isinstance(n, ast.Assign)
            and any(getattr(t, "id", None) == var for t in n.targets)]
    if len(hits) != 1:
        raise SystemExit(f"ERROR: expected one module-level {var}, found {len(hits)}")
    return hits[0]


def load(name, modname):
    spec = importlib.util.spec_from_file_location(modname, path(name))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sums(v):
    return [sum(v[c] for c in g) for g in DOMAINS]


def total(v):
    return sum(v[c] for c in ALL)


def fails(v):
    return [c for c in ALL if v[c] == 0.0]


def tier(n):
    return ('Potentially Adequate' if n <= 2 else 'Partially Adequate' if n <= 5 else 'Structurally Inadequate')


def moved(v, changes):
    w = dict(v)
    w.update(changes)
    return w


def higher(a, b):
    return [c for c in ALL if a[c] > b[c]]


def dominates(a, b):
    return all(a[c] >= b[c] for c in ALL) and any(a[c] > b[c] for c in ALL)


def enumerate_flags(v, flags):
    """Every combination of flagged calls (each at its scored value or its stated alternative).
    Returns (n_combinations, min total, max total, {tier: count}). Each flag is on its own
    criterion, so total and failure count are additive: counted exactly by convolution."""
    dist = {(0.0, 0): 1}
    for c, alt in flags.items():
        dt, df = alt - v[c], (alt == 0.0) - (v[c] == 0.0)
        new = {}
        for (t, f), n in dist.items():
            for key in ((t, f), (t + dt, f + df)):
                new[key] = new.get(key, 0) + n
        dist = new
    base_t, base_f = total(v), len(fails(v))
    tiers = {}
    for (t, f), n in dist.items():
        tiers[tier(base_f + f)] = tiers.get(tier(base_f + f), 0) + n
    return (sum(dist.values()), base_t + min(t for t, _ in dist), base_t + max(t for t, _ in dist), tiers)


